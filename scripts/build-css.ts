// Compile the report's Tailwind source (src/report/report.css) into src/report/tailwind.gen.ts, a TS string render.ts inlines,
// so report.html needs no CDN or stylesheet at view time. Run after editing report.css or report markup classes.
//
// Usage: npm run css

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

/** Compile src/report/report.css (and what it imports) with the Tailwind CLI, minified. */
export const compileCss = () =>
  execFileSync("npx", ["--no-install", "@tailwindcss/cli", "-i", "src/report/report.css", "--minify"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
  }).trim();

if (import.meta.main) {
  const css = compileCss();
  const out =
    "// Generated by `npm run css` (scripts/build-css.ts) from src/report/report.css. Do not edit by hand.\n" +
    `export const TAILWIND_CSS = ${JSON.stringify(css)};\n`;
  writeFileSync(`${root}src/report/tailwind.gen.ts`, out);
  console.log(`src/report/tailwind.gen.ts: ${css.length} bytes of CSS`);
}
